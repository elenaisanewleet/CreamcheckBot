GROUP_ORDER: List[str] = [key for key, _, _, _ in GROUPS]

GROUP_EMOJI: Dict[str, str] = {key: emoji for key, emoji, _, _ in GROUPS}

GROUP_TITLE: Dict[str, str] = {key: title for key, _, title, _ in GROUPS}

FALLBACK_GROUP = "other"


def is_valid_group(key: str) -> bool:
    return key in GROUP_EMOJI


def normalize_group(key: object) -> str:
    """Приводит ответ модели к известному ключу; незнакомое уходит в «Остальное»."""
    if not isinstance(key, str):
        return FALLBACK_GROUP
    k = key.strip().lower()
    return k if k in GROUP_EMOJI else FALLBACK_GROUP


def group_label(key: str) -> str:
    """«🧴 Силиконы» — для заголовка карточки и текста кнопки."""
    k = normalize_group(key)
    return f"{GROUP_EMOJI[k]} {GROUP_TITLE[k]}"


def groups_prompt_hint() -> str:
    """Список групп с пояснениями — вставляется в промпт, чтобы модель не выдумывала свои."""
    lines = []
    for key, _, title, hint in GROUPS:
        lines.append(f"- {key} — {title}: {hint}")
    return "\n".join(lines)
